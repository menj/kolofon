/**
 * Return the option key for a given platform slug.
 *
 * @param string $slug Platform slug.
 * @return string
 */
function social_key( $slug ) {
	return 'social_' . $slug;
}

/**
 * Normalise a raw social URL. Treats bare emails as mailto:.
 *
 * @param string $raw Raw input.
 * @return string
 */
function normalise_social_url( $raw ) {
	$raw = trim( (string) $raw );
	if ( '' === $raw ) {
		return '';
	}
	if ( is_email( $raw ) ) {
		return 'mailto:' . sanitize_email( $raw );
	}
	return esc_url_raw( $raw );
}

/**
 * Platforms with a stored URL, in registry order.
 *
 * @return array<string, array> Slug to platform meta plus `url`.
 */
function get_active_social_links() {
	$active = array();

	foreach ( get_social_platforms() as $slug => $meta ) {
		$url = opt( social_key( $slug ) );
		if ( ! empty( $url ) ) {
			$active[ $slug ] = array( 'url' => $url ) + $meta;
		}
	}

	return $active;
}

/**
 * Build the inline <svg> markup for a platform's icon.
 *
 * Shared by the profile icon row here and by the per-post share row in
 * inc/share.php, so both draw from the exact same glyph data with no
 * duplication. Falls back to a 24x24 viewBox, which every platform in the
 * registry uses except Scribd (see its `viewbox` override).
 *
 * @param array $meta Platform meta from get_social_platforms(): needs 'svg',
 *                     optionally 'viewbox'.
 * @return string
 */
function platform_icon_svg( array $meta ) {
	$viewbox = ! empty( $meta['viewbox'] ) ? $meta['viewbox'] : '0 0 24 24';

	return sprintf(
		'<svg viewBox="%s" width="22" height="22" aria-hidden="true" focusable="false">%s</svg>',
		esc_attr( $viewbox ),
		$meta['svg'] // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- static internal SVG markup.
	);
}

/**
 * Render the "Find me on:" line with icons for each populated platform.
 * Prints nothing if no platform URLs are set.
 */
function render_social_icons() {
	$active = get_active_social_links();

	if ( empty( $active ) ) {
		return;
	}

	echo '<p class="hero-social"><span class="hero-social-label">' . esc_html__( 'Find me on:', 'kolofon' ) . '</span>';
	echo '<span class="hero-social-icons">';

	foreach ( $active as $slug => $meta ) {
		$rel  = ! empty( $meta['rel'] ) ? ' rel="' . esc_attr( $meta['rel'] ) . '"' : '';
		$icon = platform_icon_svg( $meta );

		// The email address is never emitted as a plain mailto: link.
		if ( 'email' === $slug ) {
			echo protected_mailto( // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- builder escapes internally.
				$meta['url'],
				$icon,
				array(
					'class'      => 'hero-social-link k-email',
					'aria-label' => $meta['label'],
					'title'      => $meta['label'],
				)
			);
			continue;
		}

		printf(
			'<a class="hero-social-link" href="%1$s" aria-label="%2$s" title="%2$s"%3$s>%4$s</a>',
			esc_url( $meta['url'] ),
			esc_attr( $meta['label'] ),
			$rel, // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- pre-escaped above.
			$icon // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- built above.
		);
	}

	echo '</span></p>';
}

/**
 * Whether any active icon requires the Font Awesome CC BY 4.0 credit line.
 *
 * Two of the registry's icons are Font Awesome Free marks rather than the
 * public-domain Simple Icons ones the rest of the set uses: LinkedIn (no
 * Simple Icons equivalent exists, for brand-guideline reasons on their side)
 * and Scribd (never added to Simple Icons at all). CC BY 4.0 requires a
 * credit "in any reasonable manner", so the footer prints one, but only when
 * one of these two is actually in use — an unused icon in the registry
 * carries no obligation.
 *
 * @return bool
 */
function uses_attributed_icon() {
	return (bool) ( opt( 'social_linkedin' ) || opt( 'social_scribd' ) );
}
